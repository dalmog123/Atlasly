/**
 * Geolocated places worth building a trip around: cities, UNESCO sites and
 * natural wonders. Coordinates are approximate to a kilometre or so, which is
 * far more precision than a globe or a route line needs.
 *
 * Countries without an entry here are still fully usable — a trip stop can be
 * the country itself — so this list is depth, not a dependency.
 */

export type PlaceKind = 'city' | 'heritage' | 'nature';

export interface Place {
  id: string;
  name: string;
  /** ISO 3166-1 alpha-3 of the country it sits in. */
  country: string;
  lat: number;
  lng: number;
  kind: PlaceKind;
}

const p = (country: string, name: string, lat: number, lng: number, kind: PlaceKind): Place => ({
  id: `${country}-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
  name,
  country,
  lat,
  lng,
  kind,
});

